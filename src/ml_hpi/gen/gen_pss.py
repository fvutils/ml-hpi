"""PSS generator for ml-hpi (IDL -> PSS component declarations)."""
from __future__ import annotations
from collections import defaultdict
from io import StringIO
from pathlib import Path
from typing import Union

from ml_hpi.model import Interface, Method, MlHpiDoc
from .gen_base import Generator


class GenPSS(Generator):
    """Generates a ``.pss`` file per package containing ``component`` and
    ``function`` declarations."""

    def __init__(self, doc: MlHpiDoc, addr_bits: int = 64):
        super().__init__(doc)
        self.addr_bits = addr_bits

    def generate(self, outdir: Union[str, Path]) -> list[Path]:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)

        # Group interfaces by package prefix
        pkgs: dict[str, list[Interface]] = defaultdict(list)
        for iface in self.doc.spec.interfaces:
            pkgs[iface.pkg()].append(iface)

        generated: list[Path] = []
        for pkg_name, ifaces in pkgs.items():
            out = StringIO()
            out.write(f"// Auto-generated by ml-hpi GenPSS -- do not edit\n")
            out.write(f"package {pkg_name} {{\n\n")
            for iface in ifaces:
                self._write_component(out, iface)
                out.write("\n")
            out.write(f"}} // package {pkg_name}\n")

            fname = f"{pkg_name}.pss"
            outfile = outdir / fname
            outfile.write_text(out.getvalue())
            generated.append(outfile)

        return generated

    def _write_component(self, out: StringIO, iface: Interface) -> None:
        short = iface.short_name()
        if iface.extends:
            # Base name: use short name if in same package
            base_parts = iface.extends.rsplit(".", 1)
            base_short = base_parts[-1] if len(base_parts) == 2 else iface.extends
            out.write(f"  component {short} : {base_short} {{\n")
        else:
            out.write(f"  component {short} {{\n")

        for meth in iface.methods:
            self._write_function(out, meth)

        for mem in iface.members:
            self._write_member(out, mem)

        out.write(f"  }}\n")

    def _write_function(self, out: StringIO, meth: Method) -> None:
        rtype = self.pss_type(meth.rtype, self.addr_bits)
        params = ", ".join(
            f"{self.pss_type(p.type, self.addr_bits)} {p.name}"
            for p in meth.params
        )

        prefix = "target " if meth.is_target() else ""
        out.write(f"    {prefix}function {rtype} {meth.name}({params});")

        # Encode attrs as a trailing comment for round-trip fidelity
        pragmas = []
        pragmas.append("blocking=true" if meth.is_blocking() else "blocking=false")
        ll = meth.get_log_level()
        if ll is not None:
            pragmas.append(f"log_level={ll}")
        out.write(f"  // ml-hpi: {', '.join(pragmas)}")
        out.write("\n")

    def _write_member(self, out: StringIO, mem) -> None:
        mem_type = mem.type.rsplit(".", 1)[-1]
        if mem.kind == "array":
            out.write(f"    array<{mem_type}, *> {mem.name};\n")
        else:
            out.write(f"    {mem_type} {mem.name};\n")
