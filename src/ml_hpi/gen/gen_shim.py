"""Logging shim generator for ml-hpi.

For each interface, produces:
- Argument pack structs/dataclasses per method.
- Result pack structs/dataclasses per non-void method.
- A call context type.
- A logger interface.
- A logging shim class.
"""
from __future__ import annotations
from collections import defaultdict
from io import StringIO
from pathlib import Path
from typing import Union

from ml_hpi.model import Interface, Method, MlHpiDoc, LOG_LEVELS
from .gen_base import Generator


class GenShim(Generator):
    """Generates logging shim classes for all interfaces in a spec."""

    def __init__(self, doc: MlHpiDoc, lang: str = "cpp", addr_bits: int = 64):
        super().__init__(doc)
        if lang not in ("cpp", "python", "sv"):
            raise ValueError(f"Unknown lang {lang!r}")
        self.lang = lang
        self.addr_bits = addr_bits

    def generate(self, outdir: Union[str, Path]) -> list[Path]:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)

        pkgs: dict[str, list[Interface]] = defaultdict(list)
        for iface in self.doc.spec.interfaces:
            pkgs[iface.pkg()].append(iface)

        generated: list[Path] = []
        for pkg_name, ifaces in pkgs.items():
            # Assign interface IDs
            iface_ids = {iface.name: i for i, iface in enumerate(ifaces)}

            if self.lang == "cpp":
                files = self._gen_cpp(outdir, pkg_name, ifaces, iface_ids)
            elif self.lang == "python":
                files = self._gen_python(outdir, pkg_name, ifaces, iface_ids)
            else:
                files = self._gen_sv(outdir, pkg_name, ifaces, iface_ids)
            generated.extend(files)
        return generated

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _log_level_num(self, method: Method, iface: Interface) -> int:
        ll = method.effective_log_level(iface.log_level)
        return LOG_LEVELS.get(ll, 3)

    # ------------------------------------------------------------------
    # C++ generation
    # ------------------------------------------------------------------

    def _gen_cpp(self, outdir: Path, pkg: str, ifaces: list[Interface],
                 iface_ids: dict[str, int]) -> list[Path]:
        out = StringIO()
        out.write(f"// Auto-generated by ml-hpi GenShim -- do not edit\n")
        out.write(f"#pragma once\n\n")
        out.write(f"#include <cstdint>\n#include <string>\n#include <sstream>\n\n")
        out.write(f"namespace {pkg} {{\n\n")

        # Forward declare all interfaces (assume main header is included)
        for iface in ifaces:
            out.write(f"class {iface.short_name()};\n")
        out.write("\n")

        for iface in ifaces:
            self._gen_cpp_interface(out, iface, iface_ids)

        out.write(f"}} // namespace {pkg}\n")

        fname = f"{pkg}_shim.hpp"
        outfile = outdir / fname
        outfile.write_text(out.getvalue())
        return [outfile]

    def _gen_cpp_interface(self, out: StringIO, iface: Interface,
                           iface_ids: dict[str, int]) -> None:
        short = iface.short_name()
        i_id = iface_ids[iface.name]

        # Arg/result base classes
        out.write(f"// --- {short} logging infrastructure ---\n\n")
        out.write(f"struct {short}_args_base {{\n")
        out.write(f"    virtual ~{short}_args_base() = default;\n")
        out.write(f"    virtual std::string to_string() const = 0;\n}};\n\n")
        out.write(f"struct {short}_result_base {{\n")
        out.write(f"    virtual ~{short}_result_base() = default;\n")
        out.write(f"    virtual std::string to_string() const = 0;\n}};\n\n")

        # Per-method arg/result structs
        for meth in iface.methods:
            self._gen_cpp_args(out, short, meth)
            if meth.rtype != "void":
                self._gen_cpp_result(out, short, meth)

        # Call context
        out.write(f"struct {short}_call_context {{\n")
        out.write(f"    uint32_t iface_id;\n    uint32_t method_id;\n")
        out.write(f"    int32_t path;\n    uint8_t log_level;\n")
        out.write(f"    const char *iface_name;\n    const char *method_name;\n")
        out.write(f"    {short}_args_base *args = nullptr;\n")
        out.write(f"    {short}_result_base *result = nullptr;\n\n")
        out.write(f"    std::string to_string() const {{\n")
        out.write(f"        std::ostringstream ss;\n")
        out.write(f"        ss << iface_name << \".\" << method_name;\n")
        out.write(f"        if (args) ss << \"(\" << args->to_string() << \")\";\n")
        out.write(f"        if (result) ss << \" -> \" << result->to_string();\n")
        out.write(f"        return ss.str();\n    }}\n}};\n\n")

        # Logger interface
        out.write(f"class {short}Logger {{\npublic:\n")
        out.write(f"    virtual ~{short}Logger() = default;\n")
        out.write(f"    virtual void on_enter(const {short}_call_context &ctx) {{}}\n")
        out.write(f"    virtual void on_leave(const {short}_call_context &ctx) {{}}\n")
        out.write(f"}};\n\n")

        # Shim class
        if iface.extends:
            base_short = iface.extends.rsplit(".", 1)[-1]
            out.write(f"class {short}LoggingShim : public virtual {short} {{\n")
        else:
            out.write(f"class {short}LoggingShim : public virtual {short} {{\n")
        out.write(f"public:\n")
        out.write(f"    {short}LoggingShim({short} *inner, {short}Logger *logger = nullptr, uint8_t threshold = 3)\n")
        out.write(f"        : inner_(inner), logger_(logger), threshold_(threshold) {{}}\n\n")
        out.write(f"    void set_logger({short}Logger *l) {{ logger_ = l; }}\n")
        out.write(f"    void set_threshold(uint8_t t) {{ threshold_ = t; }}\n")
        out.write(f"    void set_path(int32_t p) {{ path_ = p; }}\n\n")

        for m_id, meth in enumerate(iface.methods):
            self._gen_cpp_shim_method(out, short, meth, i_id, m_id, iface)

        # Member accessors -- passthrough
        for mem in iface.members:
            mem_type = mem.type.rsplit(".", 1)[-1]
            if mem.kind == "array":
                out.write(f"    {mem_type} *{mem.name}_at(int idx) override {{ return inner_->{mem.name}_at(idx); }}\n")
                out.write(f"    int {mem.name}_size() override {{ return inner_->{mem.name}_size(); }}\n")
            else:
                out.write(f"    {mem_type} *{mem.name}() override {{ return inner_->{mem.name}(); }}\n")

        out.write(f"\nprivate:\n")
        out.write(f"    {short} *inner_;\n    {short}Logger *logger_;\n")
        out.write(f"    uint8_t threshold_;\n    int32_t path_ = -1;\n")
        out.write(f"}};\n\n")

    def _gen_cpp_args(self, out: StringIO, short: str, meth: Method) -> None:
        name = f"{short}_{meth.name}_args"
        out.write(f"struct {name} : {short}_args_base {{\n")
        for p in meth.params:
            out.write(f"    {self.cpp_type(p.type, self.addr_bits)} {p.name};\n")
        out.write(f"    std::string to_string() const override {{\n")
        out.write(f"        std::ostringstream ss;\n")
        parts = []
        for i, p in enumerate(meth.params):
            sep = '"' + (', ' if i > 0 else '') + p.name + '="'
            parts.append(f'        ss << {sep} << {p.name};\n')
        for part in parts:
            out.write(part)
        out.write(f"        return ss.str();\n    }}\n}};\n\n")

    def _gen_cpp_result(self, out: StringIO, short: str, meth: Method) -> None:
        name = f"{short}_{meth.name}_result"
        rt = self.cpp_type(meth.rtype, self.addr_bits)
        out.write(f"struct {name} : {short}_result_base {{\n")
        out.write(f"    {rt} rval;\n")
        out.write(f"    std::string to_string() const override {{\n")
        out.write(f"        std::ostringstream ss;\n")
        out.write(f'        ss << "rval=" << rval;\n')
        out.write(f"        return ss.str();\n    }}\n}};\n\n")

    def _gen_cpp_shim_method(self, out: StringIO, short: str, meth: Method,
                              i_id: int, m_id: int, iface: Interface) -> None:
        ll = self._log_level_num(meth, iface)
        rtype = self.cpp_type(meth.rtype, self.addr_bits)
        params = ", ".join(f"{self.cpp_type(p.type, self.addr_bits)} {p.name}" for p in meth.params)
        call_args = ", ".join(p.name for p in meth.params)
        args_type = f"{short}_{meth.name}_args"

        out.write(f"    {rtype} {meth.name}({params}) override {{\n")
        out.write(f"        if (logger_ && {ll} >= threshold_) {{\n")
        # Build args
        if meth.params:
            init = ", ".join(p.name for p in meth.params)
            out.write(f"            {args_type} args{{{init}}};\n")
        else:
            out.write(f"            {args_type} args;\n")
        out.write(f'            {short}_call_context ctx{{{i_id}, {m_id}, path_, {ll}, "{short}", "{meth.name}", &args, nullptr}};\n')
        out.write(f"            logger_->on_enter(ctx);\n")

        if meth.rtype == "void":
            out.write(f"            inner_->{meth.name}({call_args});\n")
            out.write(f"            logger_->on_leave(ctx);\n")
        else:
            res_type = f"{short}_{meth.name}_result"
            out.write(f"            {rtype} result = inner_->{meth.name}({call_args});\n")
            out.write(f"            {res_type} res{{result}};\n")
            out.write(f"            ctx.result = &res;\n")
            out.write(f"            logger_->on_leave(ctx);\n")
            out.write(f"            return result;\n")
        out.write(f"        }} else {{\n")
        if meth.rtype == "void":
            out.write(f"            inner_->{meth.name}({call_args});\n")
        else:
            out.write(f"            return inner_->{meth.name}({call_args});\n")
        out.write(f"        }}\n    }}\n\n")

    # ------------------------------------------------------------------
    # Python generation
    # ------------------------------------------------------------------

    def _gen_python(self, outdir: Path, pkg: str, ifaces: list[Interface],
                    iface_ids: dict[str, int]) -> list[Path]:
        out = StringIO()
        out.write(f"# Auto-generated by ml-hpi GenShim -- do not edit\n")
        out.write(f"from __future__ import annotations\n")
        out.write(f"import dataclasses\nimport typing\n\n")

        for iface in ifaces:
            self._gen_python_interface(out, iface, iface_ids)

        fname = f"{pkg}_shim.py"
        outfile = outdir / fname
        outfile.write_text(out.getvalue())
        return [outfile]

    def _gen_python_interface(self, out: StringIO, iface: Interface,
                               iface_ids: dict[str, int]) -> None:
        short = iface.short_name()
        i_id = iface_ids[iface.name]

        # Arg dataclasses
        for meth in iface.methods:
            out.write(f"@dataclasses.dataclass\nclass {short}_{meth.name}_args:\n")
            if meth.params:
                for p in meth.params:
                    out.write(f"    {p.name}: {self.python_type(p.type, 'plain', self.addr_bits)}\n")
            else:
                out.write(f"    pass\n")
            parts = ' '.join(f'{p.name}={{self.{p.name}}}' for p in meth.params)
            out.write(f'    def __str__(self) -> str:\n        return f"{parts}"\n\n')

        # Result dataclasses
        for meth in iface.methods:
            if meth.rtype != "void":
                rt = self.python_type(meth.rtype, "plain", self.addr_bits)
                out.write(f"@dataclasses.dataclass\nclass {short}_{meth.name}_result:\n")
                out.write(f"    rval: {rt}\n")
                out.write(f'    def __str__(self) -> str:\n        return f"rval={{self.rval}}"\n\n')

        # Call context
        out.write(f"@dataclasses.dataclass\nclass {short}_call_context:\n")
        out.write(f"    iface_id: int\n    method_id: int\n    path: int\n")
        out.write(f"    log_level: int\n    iface_name: str\n    method_name: str\n")
        out.write(f"    args: object | None = None\n    result: object | None = None\n")
        out.write(f"    def __str__(self) -> str:\n")
        out.write(f"        s = f\"{{self.iface_name}}.{{self.method_name}}\"\n")
        out.write(f"        if self.args is not None:\n            s += f\"({{self.args}})\"\n")
        out.write(f"        if self.result is not None:\n            s += f\" -> {{self.result}}\"\n")
        out.write(f"        return s\n\n")

        # Logger protocol
        out.write(f"class {short}Logger(typing.Protocol):\n")
        out.write(f"    def on_enter(self, ctx: {short}_call_context) -> None: ...\n")
        out.write(f"    def on_leave(self, ctx: {short}_call_context) -> None: ...\n\n")

        # Shim class
        out.write(f"class {short}LoggingShim:\n")
        out.write(f"    def __init__(self, inner, logger=None, threshold: int = 3, path: int = -1):\n")
        out.write(f"        self._inner = inner\n        self._logger = logger\n")
        out.write(f"        self._threshold = threshold\n        self._path = path\n\n")

        for m_id, meth in enumerate(iface.methods):
            self._gen_python_shim_method(out, short, meth, i_id, m_id, iface)

        # Member passthrough
        for mem in iface.members:
            if mem.kind == "array":
                out.write(f"    def {mem.name}_at(self, idx: int):\n        return self._inner.{mem.name}_at(idx)\n")
                out.write(f"    def {mem.name}_size(self) -> int:\n        return self._inner.{mem.name}_size()\n\n")
            else:
                out.write(f"    def {mem.name}(self):\n        return self._inner.{mem.name}()\n\n")

    def _gen_python_shim_method(self, out: StringIO, short: str, meth: Method,
                                 i_id: int, m_id: int, iface: Interface) -> None:
        ll = self._log_level_num(meth, iface)
        is_async = meth.is_blocking()
        params = ", ".join(p.name for p in meth.params)
        self_params = f"self, {params}" if params else "self"
        prefix = "async " if is_async else ""
        await_kw = "await " if is_async else ""
        args_cls = f"{short}_{meth.name}_args"
        args_init = ", ".join(f"{p.name}={p.name}" for p in meth.params) if meth.params else ""

        out.write(f"    {prefix}def {meth.name}({self_params}):\n")
        out.write(f"        if self._logger and {ll} >= self._threshold:\n")
        out.write(f"            args = {args_cls}({args_init})\n")
        out.write(f'            ctx = {short}_call_context({i_id}, {m_id}, self._path, {ll}, "{short}", "{meth.name}", args=args)\n')
        out.write(f"            self._logger.on_enter(ctx)\n")

        if meth.rtype == "void":
            out.write(f"            {await_kw}self._inner.{meth.name}({params})\n")
            out.write(f"            self._logger.on_leave(ctx)\n")
        else:
            res_cls = f"{short}_{meth.name}_result"
            out.write(f"            result = {await_kw}self._inner.{meth.name}({params})\n")
            out.write(f"            ctx.result = {res_cls}(rval=result)\n")
            out.write(f"            self._logger.on_leave(ctx)\n")
            out.write(f"            return result\n")

        out.write(f"        else:\n")
        if meth.rtype == "void":
            out.write(f"            {await_kw}self._inner.{meth.name}({params})\n\n")
        else:
            out.write(f"            return {await_kw}self._inner.{meth.name}({params})\n\n")

    # ------------------------------------------------------------------
    # SystemVerilog generation
    # ------------------------------------------------------------------

    def _gen_sv(self, outdir: Path, pkg: str, ifaces: list[Interface],
                iface_ids: dict[str, int]) -> list[Path]:
        out = StringIO()
        out.write(f"// Auto-generated by ml-hpi GenShim -- do not edit\n")
        out.write(f"package {pkg}_shim;\n\n")

        for iface in ifaces:
            self._gen_sv_interface(out, iface, iface_ids, pkg)

        out.write(f"endpackage\n")

        fname = f"{pkg}_shim.sv"
        outfile = outdir / fname
        outfile.write_text(out.getvalue())
        return [outfile]

    def _gen_sv_interface(self, out: StringIO, iface: Interface,
                          iface_ids: dict[str, int], pkg: str) -> None:
        short = iface.short_name()
        i_id = iface_ids[iface.name]

        # Arg classes
        for meth in iface.methods:
            out.write(f"  class {short}_{meth.name}_args;\n")
            for p in meth.params:
                out.write(f"    {self.sv_type(p.type, self.addr_bits)} {p.name};\n")
            out.write(f"    function string to_string();\n")
            parts = ", ".join(f'{p.name}=0x%0x' for p in meth.params)
            args_list = ", ".join(p.name for p in meth.params)
            if meth.params:
                out.write(f'      return $sformatf("{parts}", {args_list});\n')
            else:
                out.write(f'      return "";\n')
            out.write(f"    endfunction\n  endclass\n\n")

        # Result classes
        for meth in iface.methods:
            if meth.rtype != "void":
                rt = self.sv_type(meth.rtype, self.addr_bits)
                out.write(f"  class {short}_{meth.name}_result;\n")
                out.write(f"    {rt} rval;\n")
                out.write(f"    function string to_string();\n")
                out.write(f'      return $sformatf("rval=0x%0x", rval);\n')
                out.write(f"    endfunction\n  endclass\n\n")

        # Call context
        out.write(f"  class {short}_call_context;\n")
        out.write(f"    int unsigned iface_id;\n    int unsigned method_id;\n")
        out.write(f"    int path;\n    byte unsigned log_level;\n")
        out.write(f"    string iface_name;\n    string method_name;\n")
        out.write(f"    {short}_{iface.methods[0].name}_args args;\n" if iface.methods else "")
        out.write(f"    function string to_string();\n")
        out.write(f'      automatic string s = {{iface_name, ".", method_name}};\n')
        out.write(f"      if (args != null) s = {{s, \"(\", args.to_string(), \")\"}};\n")
        out.write(f"      return s;\n    endfunction\n  endclass\n\n")

        # Logger interface class
        out.write(f"  interface class {short}Logger;\n")
        out.write(f"    pure virtual function void on_enter({short}_call_context ctx);\n")
        out.write(f"    pure virtual function void on_leave({short}_call_context ctx);\n")
        out.write(f"  endclass\n\n")

        # Shim class
        out.write(f"  class {short}LoggingShim;\n")
        out.write(f"    {pkg}::{short} inner;\n")
        out.write(f"    {short}Logger logger;\n")
        out.write(f"    byte unsigned threshold;\n")
        out.write(f"    int path;\n\n")
        out.write(f"    function new({pkg}::{short} inner, {short}Logger logger = null, byte unsigned threshold = 3);\n")
        out.write(f"      this.inner = inner;\n      this.logger = logger;\n")
        out.write(f"      this.threshold = threshold;\n      this.path = -1;\n")
        out.write(f"    endfunction\n\n")

        for m_id, meth in enumerate(iface.methods):
            self._gen_sv_shim_method(out, short, meth, i_id, m_id, iface, iface.pkg())

        # Member passthrough
        for mem in iface.members:
            mem_type = mem.type.rsplit(".", 1)[-1]
            if mem.kind == "array":
                out.write(f"    virtual function {mem_type} {mem.name}_at(int idx);\n")
                out.write(f"      return inner.{mem.name}_at(idx);\n    endfunction\n")
                out.write(f"    virtual function int {mem.name}_size();\n")
                out.write(f"      return inner.{mem.name}_size();\n    endfunction\n\n")
            else:
                out.write(f"    virtual function {mem_type} {mem.name}();\n")
                out.write(f"      return inner.{mem.name}();\n    endfunction\n\n")

        out.write(f"  endclass\n\n")

    def _gen_sv_shim_method(self, out: StringIO, short: str, meth: Method,
                             i_id: int, m_id: int, iface: Interface, pkg: str) -> None:
        ll = self._log_level_num(meth, iface)
        is_blocking = meth.is_blocking()
        args_cls = f"{short}_{meth.name}_args"

        if is_blocking:
            # Task form
            parts = []
            has_output = meth.rtype != "void"
            if has_output:
                rtype = self.sv_type(meth.rtype, self.addr_bits)
                parts.append(f"output {rtype} rval")
            for p in meth.params:
                sv_t = self.sv_type(p.type, self.addr_bits)
                if has_output:
                    parts.append(f"input {sv_t} {p.name}")
                else:
                    parts.append(f"{sv_t} {p.name}")
            params_str = ", ".join(parts)
            out.write(f"    virtual task {meth.name}({params_str});\n")
        else:
            rtype = self.sv_type(meth.rtype, self.addr_bits)
            params_str = ", ".join(f"{self.sv_type(p.type, self.addr_bits)} {p.name}" for p in meth.params)
            out.write(f"    virtual function {rtype} {meth.name}({params_str});\n")

        out.write(f"      if (logger != null && {ll} >= threshold) begin\n")
        out.write(f"        automatic {args_cls} args = new();\n")
        out.write(f"        automatic {short}_call_context ctx = new();\n")
        for p in meth.params:
            out.write(f"        args.{p.name} = {p.name};\n")
        out.write(f"        ctx.iface_id = {i_id};\n        ctx.method_id = {m_id};\n")
        out.write(f"        ctx.path = path;\n        ctx.log_level = {ll};\n")
        out.write(f'        ctx.iface_name = "{short}";\n        ctx.method_name = "{meth.name}";\n')
        out.write(f"        logger.on_enter(ctx);\n")

        call_args = ", ".join(p.name for p in meth.params)
        if is_blocking and meth.rtype != "void":
            out.write(f"        inner.{meth.name}(rval{', ' + call_args if call_args else ''});\n")
            res_cls = f"{short}_{meth.name}_result"
            out.write(f"        begin\n          automatic {res_cls} res = new();\n")
            out.write(f"          res.rval = rval;\n          logger.on_leave(ctx);\n        end\n")
        elif is_blocking:
            out.write(f"        inner.{meth.name}({call_args});\n")
            out.write(f"        logger.on_leave(ctx);\n")
        elif meth.rtype != "void":
            res_cls = f"{short}_{meth.name}_result"
            out.write(f"        begin\n")
            rt = self.sv_type(meth.rtype, self.addr_bits)
            out.write(f"          automatic {rt} r = inner.{meth.name}({call_args});\n")
            out.write(f"          automatic {res_cls} res = new();\n")
            out.write(f"          res.rval = r;\n          logger.on_leave(ctx);\n")
            out.write(f"          return r;\n        end\n")
        else:
            out.write(f"        inner.{meth.name}({call_args});\n")
            out.write(f"        logger.on_leave(ctx);\n")

        out.write(f"      end else begin\n")
        if is_blocking and meth.rtype != "void":
            out.write(f"        inner.{meth.name}(rval{', ' + call_args if call_args else ''});\n")
        elif is_blocking:
            out.write(f"        inner.{meth.name}({call_args});\n")
        elif meth.rtype != "void":
            out.write(f"        return inner.{meth.name}({call_args});\n")
        else:
            out.write(f"        inner.{meth.name}({call_args});\n")
        out.write(f"      end\n")

        if is_blocking:
            out.write(f"    endtask\n\n")
        else:
            out.write(f"    endfunction\n\n")
