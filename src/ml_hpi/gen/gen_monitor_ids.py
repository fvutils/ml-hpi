"""Monitor ID table generator for ml-hpi."""
from __future__ import annotations
from collections import defaultdict
from io import StringIO
from pathlib import Path
from typing import Union

from ml_hpi.model import Interface, MlHpiDoc
from .gen_base import Generator


class GenMonitorIds(Generator):
    """Generates deterministic interface/method ID constant tables."""

    def __init__(self, doc: MlHpiDoc, lang: str = "cpp"):
        super().__init__(doc)
        if lang not in ("cpp", "python", "sv"):
            raise ValueError(f"Unknown lang {lang!r}")
        self.lang = lang

    def generate(self, outdir: Union[str, Path]) -> list[Path]:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)

        pkgs: dict[str, list[Interface]] = defaultdict(list)
        for iface in self.doc.spec.interfaces:
            pkgs[iface.pkg()].append(iface)

        generated: list[Path] = []
        for pkg_name, ifaces in pkgs.items():
            if self.lang == "cpp":
                text = self._gen_cpp(pkg_name, ifaces)
                fname = f"{pkg_name}_monitor_ids.hpp"
            elif self.lang == "python":
                text = self._gen_python(pkg_name, ifaces)
                fname = f"{pkg_name}_monitor_ids.py"
            else:
                text = self._gen_sv(pkg_name, ifaces)
                fname = f"{pkg_name}_monitor_ids_pkg.sv"

            outfile = outdir / fname
            outfile.write_text(text)
            generated.append(outfile)
        return generated

    def _gen_cpp(self, pkg: str, ifaces: list[Interface]) -> str:
        out = StringIO()
        out.write(f"// Auto-generated by ml-hpi GenMonitorIds -- do not edit\n")
        out.write(f"#pragma once\n\n#include <cstdint>\n\n")
        out.write(f"namespace {pkg} {{\nnamespace monitor_ids {{\n\n")

        names: list[str] = []
        method_entries: list[str] = []  # (iface_id, method_id, name)
        for i_id, iface in enumerate(ifaces):
            short = iface.short_name()
            names.append(short)
            out.write(f"constexpr uint32_t {short} = {i_id};\n")
            for m_id, meth in enumerate(iface.methods):
                out.write(f"constexpr uint32_t {short}_{meth.name} = {m_id};\n")
                method_entries.append((i_id, m_id, f"{short}.{meth.name}"))
            out.write("\n")

        # Name lookup
        out.write(f"inline const char *iface_name(uint32_t id) {{\n")
        out.write(f"    static const char *names[] = {{")
        out.write(", ".join(f'"{n}"' for n in names))
        out.write(f"}};\n")
        out.write(f"    return (id < {len(names)}) ? names[id] : \"?\";\n}}\n\n")

        out.write(f"inline const char *method_name(uint32_t iface_id, uint32_t method_id) {{\n")
        out.write(f"    switch (iface_id) {{\n")
        for i_id, iface in enumerate(ifaces):
            if not iface.methods:
                continue
            out.write(f"    case {i_id}:\n")
            out.write(f"        switch (method_id) {{\n")
            for m_id, meth in enumerate(iface.methods):
                out.write(f'        case {m_id}: return "{meth.name}";\n')
            out.write(f'        default: return "?";\n        }}\n')
        out.write(f'    default: return "?";\n    }}\n}}\n\n')

        out.write(f"}} // namespace monitor_ids\n}} // namespace {pkg}\n")
        return out.getvalue()

    def _gen_python(self, pkg: str, ifaces: list[Interface]) -> str:
        out = StringIO()
        out.write(f"# Auto-generated by ml-hpi GenMonitorIds -- do not edit\n\n")

        for i_id, iface in enumerate(ifaces):
            short = iface.short_name().upper()
            out.write(f"{short} = {i_id}\n")
            for m_id, meth in enumerate(iface.methods):
                out.write(f"{short}_{meth.name.upper()} = {m_id}\n")
            out.write("\n")

        out.write("IFACE_NAMES = {\n")
        for i_id, iface in enumerate(ifaces):
            out.write(f'    {i_id}: "{iface.short_name()}",\n')
        out.write("}\n\n")

        out.write("METHOD_NAMES = {\n")
        for i_id, iface in enumerate(ifaces):
            for m_id, meth in enumerate(iface.methods):
                out.write(f'    ({i_id}, {m_id}): "{meth.name}",\n')
        out.write("}\n")
        return out.getvalue()

    def _gen_sv(self, pkg: str, ifaces: list[Interface]) -> str:
        out = StringIO()
        out.write(f"// Auto-generated by ml-hpi GenMonitorIds -- do not edit\n")
        out.write(f"package {pkg}_monitor_ids;\n\n")

        for i_id, iface in enumerate(ifaces):
            short = iface.short_name()
            out.write(f"  localparam int unsigned {short} = {i_id};\n")
            for m_id, meth in enumerate(iface.methods):
                out.write(f"  localparam int unsigned {short}_{meth.name} = {m_id};\n")
            out.write("\n")

        # iface_name function
        out.write("  function automatic string iface_name(int unsigned id);\n")
        out.write("    case (id)\n")
        for i_id, iface in enumerate(ifaces):
            out.write(f'      {i_id}: return "{iface.short_name()}";\n')
        out.write('      default: return "?";\n')
        out.write("    endcase\n  endfunction\n\n")

        # method_name function
        out.write("  function automatic string method_name(int unsigned iface_id, int unsigned method_id);\n")
        out.write("    case (iface_id)\n")
        for i_id, iface in enumerate(ifaces):
            if not iface.methods:
                continue
            out.write(f"      {i_id}: case (method_id)\n")
            for m_id, meth in enumerate(iface.methods):
                out.write(f'        {m_id}: return "{meth.name}";\n')
            out.write('        default: return "?";\n      endcase\n')
        out.write('      default: return "?";\n')
        out.write("    endcase\n  endfunction\n\n")

        out.write(f"endpackage\n")
        return out.getvalue()
