"""SystemVerilog interface class generator for ml-hpi (IDL -> SV interface class declarations)."""
from __future__ import annotations
from collections import defaultdict
from io import StringIO
from pathlib import Path
from typing import Union

from ml_hpi.model import Interface, Method, MlHpiDoc
from .gen_base import Generator


class GenSVInterface(Generator):
    """Generates a ``.sv`` file per package containing ``interface class``
    declarations -- the SV-native view of the IDL."""

    def __init__(self, doc: MlHpiDoc, addr_bits: int = 64):
        super().__init__(doc)
        self.addr_bits = addr_bits

    def generate(self, outdir: Union[str, Path]) -> list[Path]:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)

        pkgs: dict[str, list[Interface]] = defaultdict(list)
        for iface in self.doc.spec.interfaces:
            pkgs[iface.pkg()].append(iface)

        generated: list[Path] = []
        for pkg_name, ifaces in pkgs.items():
            out = StringIO()
            out.write(f"// Auto-generated by ml-hpi GenSVInterface -- do not edit\n")
            out.write(f"package {pkg_name};\n\n")
            for iface in ifaces:
                self._write_interface_class(out, iface)
                out.write("\n")
            out.write(f"endpackage\n")

            fname = f"{pkg_name}.sv"
            outfile = outdir / fname
            outfile.write_text(out.getvalue())
            generated.append(outfile)

        return generated

    def _write_interface_class(self, out: StringIO, iface: Interface) -> None:
        short = iface.short_name()
        if iface.extends:
            base_short = iface.extends.rsplit(".", 1)[-1]
            out.write(f"  interface class {short} extends {base_short};\n")
        else:
            out.write(f"  interface class {short};\n")

        for meth in iface.methods:
            self._write_method(out, meth)

        for mem in iface.members:
            self._write_member(out, mem)

        out.write(f"  endclass\n")

    def _write_method(self, out: StringIO, meth: Method) -> None:
        if meth.is_blocking():
            self._write_blocking_method(out, meth)
        else:
            self._write_nonblocking_method(out, meth)

    def _write_nonblocking_method(self, out: StringIO, meth: Method) -> None:
        rtype = self.sv_type(meth.rtype, self.addr_bits)
        params = ", ".join(
            f"{self.sv_type(p.type, self.addr_bits)} {p.name}"
            for p in meth.params
        )
        ll = meth.get_log_level()
        pragma = f"  // ml-hpi: log_level={ll}" if ll else ""
        out.write(f"    pure virtual function {rtype} {meth.name}({params});{pragma}\n")

    def _write_blocking_method(self, out: StringIO, meth: Method) -> None:
        parts: list[str] = []
        has_output = meth.rtype != "void"
        if has_output:
            rtype = self.sv_type(meth.rtype, self.addr_bits)
            parts.append(f"output {rtype} rval")
        for p in meth.params:
            sv_t = self.sv_type(p.type, self.addr_bits)
            # Explicit 'input' after 'output' to prevent SV direction stickiness
            if has_output:
                parts.append(f"input {sv_t} {p.name}")
            else:
                parts.append(f"{sv_t} {p.name}")
        params = ", ".join(parts)
        ll = meth.get_log_level()
        pragma = f"  // ml-hpi: log_level={ll}" if ll else ""
        out.write(f"    pure virtual task {meth.name}({params});{pragma}\n")

    def _write_member(self, out: StringIO, mem) -> None:
        mem_type = mem.type.rsplit(".", 1)[-1]
        if mem.kind == "array":
            out.write(f"    pure virtual function {mem_type} {mem.name}_at(int idx);\n")
            out.write(f"    pure virtual function int {mem.name}_size();\n")
        else:
            out.write(f"    pure virtual function {mem_type} {mem.name}();\n")
