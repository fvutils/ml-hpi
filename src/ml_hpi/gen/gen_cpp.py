"""C++ generator for ml-hpi (IDL -> abstract class headers)."""
from __future__ import annotations
from collections import defaultdict
from io import StringIO
from pathlib import Path
from typing import Union

from ml_hpi.model import Interface, Method, MlHpiDoc
from .gen_base import Generator


class GenCpp(Generator):
    """Generates a ``.hpp`` file per package containing abstract classes
    with pure virtual methods inside a namespace."""

    def __init__(self, doc: MlHpiDoc, addr_bits: int = 64, emit_async: bool = True):
        super().__init__(doc)
        self.addr_bits = addr_bits
        self.emit_async = emit_async

    def generate(self, outdir: Union[str, Path]) -> list[Path]:
        outdir = Path(outdir)
        outdir.mkdir(parents=True, exist_ok=True)

        pkgs: dict[str, list[Interface]] = defaultdict(list)
        for iface in self.doc.spec.interfaces:
            pkgs[iface.pkg()].append(iface)

        generated: list[Path] = []
        for pkg_name, ifaces in pkgs.items():
            out = StringIO()
            guard = f"{pkg_name.upper()}_HPP"
            out.write(f"// Auto-generated by ml-hpi GenCpp -- do not edit\n")
            out.write(f"#pragma once\n\n")
            out.write(f"#include <cstdint>\n")
            if self.emit_async:
                out.write(f"#include <functional>\n")
            out.write(f"\n")
            out.write(f"namespace {pkg_name} {{\n\n")

            # Forward-declare all classes so order doesn't matter
            for iface in ifaces:
                out.write(f"class {iface.short_name()};\n")
            out.write("\n")

            for iface in ifaces:
                self._write_class(out, iface)
                out.write("\n")

            out.write(f"}} // namespace {pkg_name}\n")

            fname = f"{pkg_name}.hpp"
            outfile = outdir / fname
            outfile.write_text(out.getvalue())
            generated.append(outfile)

        return generated

    def _write_class(self, out: StringIO, iface: Interface) -> None:
        short = iface.short_name()
        if iface.extends:
            base_short = iface.extends.rsplit(".", 1)[-1]
            out.write(f"class {short} : public virtual {base_short} {{\n")
        else:
            out.write(f"class {short} {{\n")
        out.write(f"public:\n")
        out.write(f"    virtual ~{short}() = default;\n")

        for meth in iface.methods:
            self._write_method(out, meth)
            if self.emit_async and meth.is_blocking():
                self._write_async_method(out, meth)

        for mem in iface.members:
            self._write_member(out, mem)

        out.write(f"}};\n")

    def _write_method(self, out: StringIO, meth: Method) -> None:
        rtype = self.cpp_type(meth.rtype, self.addr_bits)
        params = ", ".join(
            f"{self.cpp_type(p.type, self.addr_bits)} {p.name}"
            for p in meth.params
        )
        ll = meth.get_log_level()
        pragma = f"  // ml-hpi: log_level={ll}" if ll else ""
        out.write(f"    virtual {rtype} {meth.name}({params}) = 0;{pragma}\n")

    def _write_async_method(self, out: StringIO, meth: Method) -> None:
        """Emit the callback-based async overload for a blocking method."""
        rtype = self.cpp_type(meth.rtype, self.addr_bits)
        parts = [
            f"{self.cpp_type(p.type, self.addr_bits)} {p.name}"
            for p in meth.params
        ]
        if rtype == "void":
            parts.append("std::function<void()> cb")
        else:
            parts.append(f"std::function<void({rtype})> cb")
        params = ", ".join(parts)
        out.write(f"    virtual void {meth.name}({params}) = 0;\n")

    def _write_member(self, out: StringIO, mem) -> None:
        mem_type = mem.type.rsplit(".", 1)[-1]
        if mem.kind == "array":
            out.write(f"    virtual {mem_type} *{mem.name}_at(int idx) = 0;\n")
            out.write(f"    virtual int {mem.name}_size() = 0;\n")
        else:
            out.write(f"    virtual {mem_type} *{mem.name}() = 0;\n")
